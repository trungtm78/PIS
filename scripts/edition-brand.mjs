// The names of the product, written once per edition (the `brand` of its edition manifest: `packages/kernel/src/edition.ts` for the public edition, `packages/edition-enterprise/src/manifest.ts` for the
// enterprise one) and carried to the places that cannot read a TypeScript manifest: the phone (Dart constants, the label under the icon of Android and of iOS) and the files of the web that cannot hold a key
// (the static `index.html`, the texts of the service worker). Those places are GENERATED, or checked against the manifest, so a name is never typed twice:
//
//   node scripts/edition-brand.mjs            checks that every generated file and every static name equals the manifest (exit 1 on a drift; `npm run edition:check` runs the same check)
//   node scripts/edition-brand.mjs --write    rewrites the generated files from the manifests
//
// The public edition shows no code name; the enterprise edition keeps its own identity. Nothing here knows a name: every text is read from a manifest.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const DEFAULT_ROOT = resolve(SCRIPT_DIR, '..');

const PUBLIC_MANIFEST = 'packages/kernel/src/edition.ts';
const ENTERPRISE_MANIFEST = 'packages/edition-enterprise/src/manifest.ts';
export const PUBLIC_DART = 'apps/mobile/lib/core/edition/edition_brand.g.dart';
export const ENTERPRISE_DART = 'apps/mobile/lib/editions/enterprise/enterprise_brand.g.dart';
const ANDROID_PUBLIC = 'apps/mobile/android/app/src/main/res';
const ANDROID_ENTERPRISE = 'apps/mobile/android/app/src/enterprise/res';
const INFO_PLIST = 'apps/mobile/ios/Runner/Info.plist';
const INDEX_HTML = 'apps/web/index.html';
const SW_TEXTS = 'apps/web/src/pwa/sw-texts.json';

const lf = (text) => text.replace(/\r\n/g, '\n');

/** A Dart single-quoted string literal. */
export const dartString = (text) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')}'`;

/** The text of an Android string resource (an apostrophe and a quote are escaped, the markup characters are entities). */
export const androidText = (text) =>
  text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"');

const upperFirst = (text) => text.charAt(0).toUpperCase() + text.slice(1);

function dartConstants(prefix, brand, productName) {
  const rows = [];
  const add = (name, texts) => {
    for (const [suffix, language] of [['Vi', 'vi'], ['En', 'en']]) rows.push(`const String k${upperFirst(prefix)}${name}${suffix} = ${dartString(texts[language])};`);
  };
  if (productName !== undefined) add('ProductName', productName);
  add('LauncherName', brand.launcherName);
  add('ShortName', brand.shortName);
  add('LogoAlt', brand.logoAlt);
  add('Tagline', brand.tagline);
  return rows.join('\n');
}

function dartFile(source, prefix, brand, productName) {
  return `// GENERATED by scripts/edition-brand.mjs from the \`brand\` of the manifest in ${source}. Do not edit; run \`node scripts/edition-brand.mjs --write\`.
// The names of the ${prefix} edition, as the manifest says them: the product, the name under the icon of the phone, the short name, the label of the logo and the tagline of the sign-in screens.
${dartConstants(prefix, brand, productName)}
`;
}

function androidFile(comment, name) {
  return `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- ${comment} GENERATED by scripts/edition-brand.mjs from the launcher name of the edition manifest; an XML comment may not hold a double dash, so see that script for the option that rewrites it. -->
    <string name="app_name">${androidText(name)}</string>
</resources>
`;
}

async function loadManifests(root) {
  const manifests = {};
  if (existsSync(join(root, PUBLIC_MANIFEST))) manifests.public = (await import(pathToFileURL(join(root, PUBLIC_MANIFEST)).href)).PUBLIC_EDITION_MANIFEST;
  if (existsSync(join(root, ENTERPRISE_MANIFEST))) manifests.enterprise = (await import(pathToFileURL(join(root, ENTERPRISE_MANIFEST)).href)).ENTERPRISE_EDITION_MANIFEST;
  return manifests;
}

/** The files this script generates, `{ path, text }`, from the manifests under `root` (none for an edition whose manifest is absent). */
export async function generatedFiles(root = DEFAULT_ROOT) {
  const { public: pub, enterprise } = await loadManifests(root);
  const files = [];
  if (pub?.brand !== undefined) {
    files.push({ path: PUBLIC_DART, text: dartFile(PUBLIC_MANIFEST, 'public', pub.brand, pub.productName) });
    files.push({ path: `${ANDROID_PUBLIC}/values/strings.xml`, text: androidFile('The name of the application under its icon: the public edition. The enterprise build overrides it from src/enterprise/res.', pub.brand.launcherName.vi) });
    files.push({ path: `${ANDROID_PUBLIC}/values-en/strings.xml`, text: androidFile('The name under the icon on a phone set to English: the public edition.', pub.brand.launcherName.en) });
  }
  if (enterprise?.brand !== undefined) {
    files.push({ path: ENTERPRISE_DART, text: dartFile(ENTERPRISE_MANIFEST, 'enterprise', enterprise.brand, undefined) });
    files.push({ path: `${ANDROID_ENTERPRISE}/values/strings.xml`, text: androidFile('The name of the application under its icon in a build made as the enterprise edition (MACHVON_EDITION=enterprise).', enterprise.brand.launcherName.vi) });
    // Always: the main resources carry an English name of their own, and Android picks a locale folder before the default of the enterprise build.
    files.push({ path: `${ANDROID_ENTERPRISE}/values-en/strings.xml`, text: androidFile('The name under the icon on a phone set to English: the enterprise edition.', enterprise.brand.launcherName.en) });
  }
  return files;
}

const PLIST_DISPLAY_NAME = /(<key>CFBundleDisplayName<\/key>\s*<string>)([^<]*)(<\/string>)/;

/** The names the static files of the product carry, read from the files (`undefined` for a file that is missing or does not say it). */
export function staticNames(root) {
  const read = (path) => (existsSync(join(root, path)) ? readFileSync(join(root, path), 'utf8') : undefined);
  const html = read(INDEX_HTML);
  const plist = read(INFO_PLIST);
  const sw = read(SW_TEXTS);
  const swJson = sw === undefined ? undefined : JSON.parse(sw);
  return {
    htmlTitle: html === undefined ? undefined : /<title>([^<]*)<\/title>/.exec(html)?.[1],
    htmlBootName: html === undefined ? undefined : /<p class="boot-name">([^<]*)<\/p>/.exec(html)?.[1],
    plistDisplayName: plist === undefined ? undefined : PLIST_DISPLAY_NAME.exec(plist)?.[2],
    swAppName: swJson === undefined ? undefined : swJson.vi?.appName ?? swJson.appName,
    swAppNameEn: swJson === undefined ? undefined : swJson.en?.appName,
  };
}

/** What is not what the manifests say: a generated file that differs, a static name that is not the product name or the launcher name of the public edition. */
export async function brandDrift(root = DEFAULT_ROOT) {
  const { public: pub } = await loadManifests(root);
  const drift = [];
  for (const file of await generatedFiles(root)) {
    const target = join(root, file.path);
    if (!existsSync(target)) drift.push({ file: file.path, message: 'is missing; run node scripts/edition-brand.mjs --write' });
    else if (lf(readFileSync(target, 'utf8')) !== file.text) drift.push({ file: file.path, message: 'is not what the edition manifest says; run node scripts/edition-brand.mjs --write' });
  }
  if (pub?.brand !== undefined) {
    const names = staticNames(root);
    const expect = (file, label, held, wanted) => {
      if (held !== undefined && held !== wanted) drift.push({ file, message: `${label} ("${held}") must equal the manifest of the public edition ("${wanted}")` });
    };
    expect(INDEX_HTML, 'the title', names.htmlTitle, pub.productName.vi);
    expect(INDEX_HTML, 'the name on the first paint', names.htmlBootName, pub.productName.vi);
    expect(INFO_PLIST, 'CFBundleDisplayName', names.plistDisplayName, pub.brand.launcherName.vi);
    expect(SW_TEXTS, 'the application name', names.swAppName, pub.productName.vi);
    expect(SW_TEXTS, 'the English application name', names.swAppNameEn, pub.productName.en);
  }
  return drift;
}

/** Writes the generated files and the display name of iOS; keeps the line endings of a file that exists. */
export async function writeBrand(root = DEFAULT_ROOT) {
  const written = [];
  for (const file of await generatedFiles(root)) {
    const target = join(root, file.path);
    const crlf = existsSync(target) && readFileSync(target, 'utf8').includes('\r\n');
    const text = crlf ? file.text.replace(/\n/g, '\r\n') : file.text;
    if (existsSync(target) && readFileSync(target, 'utf8') === text) continue;
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, text);
    written.push(file.path);
  }
  const { public: pub } = await loadManifests(root);
  const plist = join(root, INFO_PLIST);
  if (pub?.brand !== undefined && existsSync(plist)) {
    const current = readFileSync(plist, 'utf8');
    const next = current.replace(PLIST_DISPLAY_NAME, (_all, head, _name, tail) => `${head}${pub.brand.launcherName.vi.replace(/&/g, '&amp;').replace(/</g, '&lt;')}${tail}`);
    if (next !== current) {
      writeFileSync(plist, next);
      written.push(INFO_PLIST);
    }
  }
  return written;
}

export async function main(argv = process.argv.slice(2), write = (line) => process.stdout.write(`${line}\n`), root = DEFAULT_ROOT) {
  if (argv.includes('--write')) {
    const written = await writeBrand(root);
    for (const path of written) write(`wrote ${path}`);
    write(written.length === 0 ? 'the generated names are current' : `${written.length} file(s) written`);
    return 0;
  }
  const drift = await brandDrift(root);
  for (const entry of drift) write(`BRAND_DRIFT: ${entry.file}: ${entry.message}`);
  write(drift.length === 0 ? 'the names of the product equal the edition manifests' : `${drift.length} name(s) differ from the edition manifests`);
  return drift.length === 0 ? 0 : 1;
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exit(await main());
