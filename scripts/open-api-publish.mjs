// Publishes the OpenAPI subset for external readers (INT-1): the operations of the contract marked `x-open-api: true`, the schemas they reach and the one security scheme (OAuth 2 client credentials).
// It writes two files from the same document: the module the API serves (`apps/api/src/modules/int/open-api-document.generated.ts`) and the file handed to external readers (`docs/open-api/openapi.json`).
// `--check` writes nothing and fails (exit 1) when either file is not what the contract says, so a change of the contract cannot leave the published document behind.
// The subset is built by the kernel (`packages/kernel/src/open-api-document.ts`, loaded as TypeScript by Node), so there is one definition of what is published.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const DEFAULT_ROOT = resolve(SCRIPT_DIR, '..');
const CONTRACT = 'Design/MACHVON_Design/03_Engineering/openapi.json';
const KERNEL_DOCUMENT = 'packages/kernel/src/open-api-document.ts';
const MODULE_FILE = 'apps/api/src/modules/int/open-api-document.generated.ts';
const PUBLIC_FILE = 'docs/open-api/openapi.json';

export const OPEN_API_INFO = {
  title: 'MACHVON open API',
  version: '1.0.0',
  description:
    'Read-only access for machines. Exchange a client id and secret for a short-lived token at /open/v1/token (OAuth 2 client credentials), then call the operations below with it as a Bearer token. Every call is limited by the rate of the account, needs the scope the operation names, and is written to the access log of the organization. The datasets are read from frozen snapshots and only while the organization has switched them on and their data product is certified.',
};

const lf = (text) => text.replace(/\r\n/g, '\n');

export async function publishedFiles(root = DEFAULT_ROOT) {
  const { openApiSubsetOf } = await import(pathToFileURL(join(root, KERNEL_DOCUMENT)).href);
  const full = JSON.parse(readFileSync(join(root, CONTRACT), 'utf8'));
  const { document, operations } = openApiSubsetOf(full, OPEN_API_INFO);
  const json = `${JSON.stringify(document, null, 2)}\n`;
  const module = [
    '// Generated by scripts/open-api-publish.mjs from Design/MACHVON_Design/03_Engineering/openapi.json (the operations marked x-open-api). Do not edit; run `node scripts/open-api-publish.mjs`.',
    `export const OPEN_API_DOCUMENT: Readonly<Record<string, unknown>> = ${JSON.stringify(document, null, 2)};`,
    `export const OPEN_API_OPERATIONS: ReadonlyArray<{ id: string; method: string; path: string; scope: string | null }> = ${JSON.stringify(operations, null, 2)};`,
    '',
  ].join('\n');
  return [
    { path: PUBLIC_FILE, text: json },
    { path: MODULE_FILE, text: module },
  ];
}

export async function main(argv, { log = console.log, root = DEFAULT_ROOT } = {}) {
  const { values } = parseArgs({ args: argv, options: { check: { type: 'boolean', default: false } } });
  const files = await publishedFiles(root);
  const stale = [];
  for (const file of files) {
    const target = join(root, file.path);
    const current = existsSync(target) ? lf(readFileSync(target, 'utf8')) : undefined;
    if (current === file.text) continue;
    stale.push(file.path);
    if (!values.check) {
      mkdirSync(dirname(target), { recursive: true });
      writeFileSync(target, file.text);
    }
  }
  if (values.check) {
    for (const path of stale) log(`${path} is not what the contract says; run node scripts/open-api-publish.mjs`);
    log(stale.length === 0 ? 'open API document is current' : `${stale.length} file(s) are stale`);
    return stale.length === 0 ? 0 : 1;
  }
  log(stale.length === 0 ? 'open API document unchanged' : `wrote ${stale.join(', ')}`);
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  process.exitCode = await main(process.argv.slice(2));
}
