// Turns the owner's dashboard template (one self-contained HTML file: fonts, d3, the data, the engine, the charts, the boot code) into the
// files the web screen is built from (apps/web/src/screens/dash). The template itself is a customer document and is not committed
// (Design/Requirments is ignored); what this script writes is. Run it again when the owner hands over a new template:
//   node scripts/dashboard/import-template.mjs "Design/Requirments/Dashbroad_Final/dashboard-ca-mau.html"
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'apps/web/src/screens/dash');
const SCOPE = '.dash9';

const source = process.argv[2];
if (!source) { console.error('usage: node scripts/dashboard/import-template.mjs <template.html>'); process.exit(2); }
const html = readFileSync(resolve(ROOT, source), 'utf8');

const scripts = [...html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)].map((m) => m[1]);
const pick = (mark) => { const found = scripts.find((s) => s.includes(mark)); if (!found) throw new Error(`the template has no script with "${mark}"`); return found; };
const must = (text, from, to) => { if (!text.includes(from)) throw new Error(`the template no longer has: ${from.slice(0, 70)}`); return text.split(from).join(to); };
const HEADER = (what) => `// GENERATED by scripts/dashboard/import-template.mjs from the owner's dashboard template: ${what}. Do not edit by hand; change the template and run the script again.\n`;

// ---- the data of the template: the mock tables ----------------------------------------------------------------------------
const db = new Function(`${pick('const DB=')};return DB;`)();
for (const root of db.nv_goc) root.van_ban = root.van_ban.replace(' (mô phỏng)', '');
db.moc_thoi_gian[0].ghi_chu = '';

// ---- the engine: every figure of the nine pages, computed from the tables ---------------------------------------------------
let engine = pick('function invest(DB');
engine = must(engine, "if (typeof module !== 'undefined') module.exports = E; else root.E = E;", 'root.E = E;');
engine = must(engine, "})(typeof window !== 'undefined' ? window : globalThis);", '})(HOLDER);');
engine = `${HEADER('the engine (every figure of the pages, from the tables)')}/* eslint-disable */
const HOLDER = {};\n${engine}\nexport const E = HOLDER.E;\n`;

// ---- the charts and the nine pages --------------------------------------------------------------------------------------------
let viz = pick('const PAGES = [];');
viz = must(viz, 'document.body.innerHTML = `<div class="pg">', 'host.innerHTML = `<div class="pg">');
viz = must(viz, "document.getElementById('b' + j)", "host.querySelector('#b' + j)");
viz = must(viz, '<div class="demo">DỮ LIỆU MINH HỌA</div>', '');
viz = must(viz, ' · Số liệu minh họa</span>', '</span>');
viz = must(viz, ' (ngưỡng minh họa theo mockup)', '');
viz = must(viz, ".replace(' (mô phỏng)', '')", '');
viz = must(viz, '<span class="${j === i ? \'on\' : \'\'}">${q.name}</span>', '<span class="${j === i ? \'on\' : \'\'}" data-pg="${j}" role="tab" tabindex="0" aria-selected="${j === i}">${q.name}</span>');
viz = must(viz, 'window.RENDER = render; window.NPAGES = PAGES.length; window.PNAMES = PAGES.map((p) => p.name);', 'return { render, count: PAGES.length, names: PAGES.map((p) => p.name) };');
if (/\b(document|window)\./.test(viz)) throw new Error('the charts of the template reach for the document or the window somewhere new: scope it to the host first');
viz = `${HEADER('the charts and the nine pages')}/* eslint-disable */\nexport function createViz(d3, E, DB, host) {\n${viz}\n}\n`;

// ---- the stylesheet, scoped to the screen ---------------------------------------------------------------------------------------
const css = html.match(/<style>([\s\S]*?)<\/style>/)[1].replace(/@font-face\{[^}]*\}/g, '');
if (css.includes('@')) throw new Error('the stylesheet of the template has an at-rule this script does not scope');
const scoped = [...css.matchAll(/([^{}]+)\{([^{}]*)\}/g)].map(([, selectors, body]) => {
  const list = selectors.split(',').map((s) => s.trim()).filter((s) => s && s !== 'html' && s !== 'body');
  if (!list.length) return '';
  return `${list.map((s) => (s === '*' ? `${SCOPE} *` : `${SCOPE} ${s}`)).join(',')}{${body.trim()}}`;
}).filter(Boolean).join('\n');
const sheet = `/* GENERATED by scripts/dashboard/import-template.mjs from the owner's dashboard template; every rule is scoped to ${SCOPE} so that it reaches no other screen. */\n${scoped}\n`;

mkdirSync(join(OUT, 'template'), { recursive: true });
mkdirSync(join(OUT, 'data'), { recursive: true });
writeFileSync(join(OUT, 'template/engine.js'), engine);
writeFileSync(join(OUT, 'template/viz.js'), viz);
writeFileSync(join(OUT, 'template/dash.css'), sheet);
writeFileSync(join(OUT, 'data/mock.json'), `${JSON.stringify(db)}\n`);
console.log('written', { tables: Object.fromEntries(Object.entries(db).map(([k, v]) => [k, v.length])), engine: engine.length, viz: viz.length, css: sheet.length });
