// Maps every operationId to the module it belongs to: its first tag, else the module of its resource (RESOURCE_MODULES), else the only module whose tagged operations share the first segment of its permission; an operation
// that none of these places has none. A support access grant is scoped by module (ST-SAS-015).
export function generateModules(doc: OpenApiDocument): Record<string, string> {
  const entries = listOperations(doc);
  const tagOf = (operation: OpenApiOperation): string | undefined => {
    const tags = operation.tags;
    const first = Array.isArray(tags) ? tags[0] : undefined;
    return typeof first === 'string' && first !== '' ? first : undefined;
  };
  const prefixOf = (operation: OpenApiOperation): string => String(operation['x-permission']).split('.')[0] ?? '';
  const owners = new Map<string, Set<string>>();
  for (const { operation } of entries) {
    const tag = tagOf(operation);
    if (tag !== undefined) owners.set(prefixOf(operation), (owners.get(prefixOf(operation)) ?? new Set<string>()).add(tag));
  }
  const modules: Record<string, string> = {};
  for (const { id, operation } of entries) {
    const sole = owners.get(prefixOf(operation));
    const module = tagOf(operation) ?? RESOURCE_MODULES[prefixOf(operation)] ?? (sole?.size === 1 ? [...sole][0] : undefined);
    if (module !== undefined) modules[id] = module;
  }
  return modules;
}

export interface OperationDescriptor {
  method: string;
  path: string;
  /** The operation declares an If-Match header parameter: the caller must send the version it saw. */
  versioned: boolean;
  stepUp: string | null;
  permission: string;
}

const IF_MATCH_HEADER = 'if-match';
const PARAMETER_REF_PREFIX = '#/components/parameters/';

// Names of the parameters of an operation, following references into components.parameters.
function parameterNames(operation: OpenApiOperation, doc: OpenApiDocument, requiredOnly = false): string[] {
  const shared = (doc.components?.parameters ?? {}) as Record<string, { name?: unknown; required?: unknown }>;
  const parameters = Array.isArray(operation.parameters) ? (operation.parameters as Array<{ name?: unknown; required?: unknown; $ref?: unknown }>) : [];
  const names: string[] = [];
  for (const parameter of parameters) {
    const resolved = typeof parameter.$ref === 'string' && parameter.$ref.startsWith(PARAMETER_REF_PREFIX)
      ? shared[parameter.$ref.slice(PARAMETER_REF_PREFIX.length)]
      : parameter;
    // An optional parameter is not part of the protocol of the operation: a client is not asked for it.
    if (typeof resolved?.name === 'string' && (requiredOnly ? resolved.required === true : true)) names.push(resolved.name);
  }
  return names;
}

// Describes every operation for clients: how to call it and which header protocol it follows.
export function generateOperations(doc: OpenApiDocument): Record<string, OperationDescriptor> {
  const operations: Record<string, OperationDescriptor> = {};
  const permissions = generatePermissions(doc);
  const stepUp = generateStepUp(doc);
  for (const { id, method, path, operation } of listOperations(doc)) {
    if (Object.hasOwn(operations, id)) throw new Error(`Duplicate operationId: ${id}`);
    operations[id] = {
      method,
      path,
      // Versioned means the request must carry If-Match: a record that is created may declare the header as optional (it has no version yet).
      versioned: parameterNames(operation, doc, true).some((name) => name.toLowerCase() === IF_MATCH_HEADER),
      stepUp: stepUp[id] ?? null,
      permission: permissions[id] ?? '',
    };
  }
  return operations;
}

export function renderOperationsModule(operations: Record<string, OperationDescriptor>): string {
  const lines = Object.keys(operations)
    .sort()
    .map((operationId) => {
      const descriptor = operations[operationId] as OperationDescriptor;
      const fields = [
        `method: ${JSON.stringify(descriptor.method)}`,
        `path: ${JSON.stringify(descriptor.path)}`,
        `versioned: ${descriptor.versioned}`,
        `stepUp: ${JSON.stringify(descriptor.stepUp)}`,
        `permission: ${JSON.stringify(descriptor.permission)}`,
      ];
      return `  ${JSON.stringify(operationId)}: { ${fields.join(', ')} },`;
    });
  return [
    GENERATED_BANNER.trimEnd(),
    'export const OPERATIONS = {',
    ...lines,
    '} as const;',
    '',
    'export type OperationName = keyof typeof OPERATIONS;',
    '',
  ].join('\n');
}

function renderTable(name: string, table: Record<string, string>): string[] {
  const lines = Object.keys(table)
    .sort()
    .map((operationId) => `  ${JSON.stringify(operationId)}: ${JSON.stringify(table[operationId])},`);
  return [`export const ${name} = {`, ...lines, '} as const;', ''];
}

export function renderPermissionsModule(
  permissions: Record<string, string>,
  stepUp: Record<string, string> = {},
  planes: Record<string, string> = {},
  modules: Record<string, string> = {},
): string {
  return [
    GENERATED_BANNER.trimEnd(),
    ...renderTable('PERMISSIONS', permissions),
    'export type OperationId = keyof typeof PERMISSIONS;',
    '',
    ...renderTable('STEP_UP', stepUp),
    ...renderTable('PLANES', planes),
    ...renderTable('MODULES', modules),
  ].join('\n');
}

// openapi-typescript is ESM only, so it is loaded lazily with a dynamic import.
export async function generateTypes(doc: OpenApiDocument): Promise<string> {
  const { default: openapiTS, astToString } = await import('openapi-typescript');
  const ast = await openapiTS(doc as unknown as OpenAPI3);
  return `${GENERATED_BANNER}${astToString(ast)}`.replace(/\r\n/g, '\n').replace(/\n*$/, '\n');
}

export interface Io {
  log: (line: string) => void;
}

const USAGE = 'Usage: generate.ts --spec <openapi.json> --out <directory> [--dart-out <directory>] [--check]';

const stdoutIo: Io = { log: (line) => process.stdout.write(`${line}\n`) };

function normalizeEol(text: string): string {
  return text.replace(/\r\n/g, '\n');
}

// Generates the committed outputs, or with --check compares them and fails on any difference.
// Exit codes: 0 ok, 1 lint or drift failure, 2 usage error.
export async function main(argv: string[], io: Io = stdoutIo): Promise<number> {
  const { values } = parseArgs({
    args: argv,
    options: { spec: { type: 'string' }, out: { type: 'string' }, 'dart-out': { type: 'string' }, check: { type: 'boolean', default: false } },
  });
  if (values.spec === undefined || values.out === undefined) {
    io.log(`--spec and --out are required. ${USAGE}`);
    return 2;
  }
  const doc = JSON.parse(readFileSync(resolve(values.spec), 'utf8')) as OpenApiDocument;
  const findings = lintOpenApi(doc);
  for (const finding of findings) io.log(`${finding.rule}: ${finding.operationId}`);
  if (findings.length > 0) return 1;

  const outputs: Array<{ directory: string; name: string; content: string }> = Object.entries({
    [PERMISSIONS_FILE]: renderPermissionsModule(generatePermissions(doc), generateStepUp(doc), generatePlanes(doc), generateModules(doc)),
    [OPERATIONS_FILE]: renderOperationsModule(generateOperations(doc)),
    [REQUEST_SCHEMAS_FILE]: renderRequestSchemasModule(generateRequestSchemas(doc)),
    [TYPES_FILE]: await generateTypes(doc),
  }).map(([name, content]) => ({ directory: resolve(values.out as string), name, content }));
  if (values['dart-out'] !== undefined) {
    const dart = generateDart(doc);
    const directory = resolve(values['dart-out']);
    outputs.push(
      { directory, name: DART_OPERATIONS_FILE, content: dart.operations },
      { directory, name: DART_REQUESTS_FILE, content: dart.requests },
      { directory, name: DART_COMMANDS_FILE, content: dart.commands },
      { directory, name: DART_RESPONSES_FILE, content: dart.responses },
      // The package keeps its test data beside its tests: lib/src is two levels below the package root.
      { directory: resolve(directory, '..', '..', 'test', 'fixtures'), name: DART_RESPONSE_FIXTURES_FILE, content: dart.responseFixtures },
    );
  }
  if (!values.check) {
    for (const { directory, name, content } of outputs) {
      mkdirSync(directory, { recursive: true });
      writeFileSync(join(directory, name), content);
    }
    return 0;
  }
  const stale = outputs
    .filter(({ directory, name, content }) => {
      const path = join(directory, name);
      return !existsSync(path) || normalizeEol(readFileSync(path, 'utf8')) !== content;
    })
    .map(({ name }) => name);
  for (const name of stale) io.log(`${name} is out of date; run \`npm run contracts:generate\``);
  return stale.length === 0 ? 0 : 1;
}

// Runs only when started as a script (node src/generate.ts), never when imported by tests.
if (process.argv[1] !== undefined && /[\\/]generate\.ts$/.test(process.argv[1])) {
  main(process.argv.slice(2)).then(
    (code) => {
      process.exitCode = code;
    },
    (error: unknown) => {
      process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
      process.exitCode = 1;
    },
  );
}
