const GENERATED_BANNER = '// Generated by packages/contracts/src/generate.ts from openapi.json. Do not edit; run `npm run contracts:generate`.\n';

// Maps operationId to its x-permission value.
export function generatePermissions(doc: OpenApiDocument): Record<string, string> {
  const permissions: Record<string, string> = {};
  for (const { id, operation } of listOperations(doc)) {
    const permission = operation['x-permission'];
    if (typeof permission !== 'string' || permission === '') throw new Error(`${id} has no x-permission`);
    if (Object.hasOwn(permissions, id)) throw new Error(`Duplicate operationId: ${id}`);
    permissions[id] = permission;
  }
  return permissions;
}

const STEP_UP_LEVELS: readonly string[] = ['aal2'];
const PLANE_NAMES: readonly string[] = ['tenant', 'control', 'internal', 'edge'];
const DEFAULT_PLANE = 'tenant';

// Maps operationId to its x-step-up level; only operations that require step-up appear.
export function generateStepUp(doc: OpenApiDocument): Record<string, string> {
  const stepUp: Record<string, string> = {};
  for (const { id, operation } of listOperations(doc)) {
    const level = operation['x-step-up'];
    if (level === undefined) continue;
    if (typeof level !== 'string' || !STEP_UP_LEVELS.includes(level)) throw new Error(`${id} has an unsupported x-step-up`);
    stepUp[id] = level;
  }
  return stepUp;
}

// Maps every operationId to its x-plane; an operation without one belongs to the tenant plane.
export function generatePlanes(doc: OpenApiDocument): Record<string, string> {
  const planes: Record<string, string> = {};
  for (const { id, operation } of listOperations(doc)) {
    const plane = operation['x-plane'] ?? DEFAULT_PLANE;
    if (typeof plane !== 'string' || !PLANE_NAMES.includes(plane)) throw new Error(`${id} has an unsupported x-plane`);
    planes[id] = plane;
  }
  return planes;
}

// The module of the resource reads and the other operations that carry no tag, by the first segment of their permission. A resource that is not named here, and whose prefix no tagged operation owns alone, belongs to no
// module: no support access grant reaches it (a grant fails closed). Left out on purpose: `proposal`, `device_registration`, `outbox_event`, `audit_event` (the audit trail, the devices of a person and the internals of the platform).
