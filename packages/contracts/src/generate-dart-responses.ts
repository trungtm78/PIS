import { listOperations } from './openapi-document.ts';
import type { OpenApiDocument } from './openapi-document.ts';

export const DART_RESPONSES_FILE = 'responses.generated.dart';
export const DART_RESPONSE_FIXTURES_FILE = 'responses.fixtures.json';

export interface DartResponses {
  /** `responses.generated.dart`: one class for each response shape and a decoder for each operation. */
  responses: string;
  /** `responses.fixtures.json`: for each operation, a response that satisfies the contract, for the Dart contract test to read back. */
  fixtures: string;
}

const BANNER = '// Generated by packages/contracts/src/generate-dart-responses.ts from openapi.json. Do not edit; run `npm run contracts:generate`.';
const REF_PREFIX = '#/components/schemas/';
const RESERVED = new Set(
  (
    'abstract as assert async await base break case catch class const continue covariant default deferred do dynamic else enum ' +
    'export extends extension external factory false final finally for Function get hide if implements import in interface is ' +
    'late library mixin new null of on operator part required rethrow return sealed set show static super switch sync this ' +
    'throw true try type typedef var void when while with yield hashCode runtimeType toString noSuchMethod toJson extra'
  ).split(' '),
);
/** Deeper than this a sample leaves out what it may and stops at lists, so that a schema that contains itself ends. */
const SAMPLE_DEPTH = 6;
const SAMPLE_UUID = '00000000-0000-4000-8000-000000000001';

type Node = Record<string, unknown>;

function asNode(value: unknown): Node | undefined {
  return typeof value === 'object' && value !== null && !Array.isArray(value) ? (value as Node) : undefined;
}

function words(text: string): string[] {
  return text.split(/[^A-Za-z0-9]+/).filter((word) => word !== '');
}

function camel(text: string): string {
  const [first = '', ...rest] = words(text);
  const joined = first.charAt(0).toLowerCase() + first.slice(1) + rest.map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join('');
  return /^[0-9]/.test(joined) ? `n${joined}` : joined;
}

function pascal(text: string): string {
  const name = words(text).map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join('');
  return /^[0-9]/.test(name) ? `N${name}` : name;
}

function safe(name: string): string {
  return RESERVED.has(name) ? `${name}_` : name;
}

function quote(text: string): string {
  return `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;
}

/** The schema with its `allOf` parts merged into one object schema (properties and required members; the later part wins). */
function flatten(schema: Node, schemas: Record<string, Node>): Node {
  const parts = Array.isArray(schema.allOf) ? schema.allOf : undefined;
  if (parts === undefined) return schema;
  const merged: Node = { ...schema, type: 'object', properties: { ...asNode(schema.properties) }, required: [...(Array.isArray(schema.required) ? schema.required : [])] };
  delete merged.allOf;
  for (const part of parts) {
    const node = asNode(part) ?? {};
    const ref = typeof node.$ref === 'string' && node.$ref.startsWith(REF_PREFIX) ? node.$ref.slice(REF_PREFIX.length) : undefined;
    const resolved = flatten(ref === undefined ? node : (schemas[ref] ?? {}), schemas);
    Object.assign(merged.properties as Node, asNode(resolved.properties));
    (merged.required as unknown[]).push(...(Array.isArray(resolved.required) ? resolved.required : []));
    if (resolved.additionalProperties === false) merged.additionalProperties = false;
  }
  return merged;
}

interface Kind {
  /** The one JSON type of the schema, `any` when it is open or a choice, and whether `null` is allowed. */
  type: string;
  nullable: boolean;
}

function kindOf(schema: Node): Kind {
  const declared = Array.isArray(schema.type) ? schema.type.map(String) : typeof schema.type === 'string' ? [schema.type] : [];
  const nullable = schema.nullable === true || declared.includes('null');
  const types = declared.filter((type) => type !== 'null');
  if (Array.isArray(schema.oneOf) || Array.isArray(schema.anyOf) || types.length > 1) return { type: 'any', nullable };
  if (types.length === 0) return { type: asNode(schema.properties) !== undefined ? 'object' : 'any', nullable };
  return { type: types[0] as string, nullable };
}

/** How a value of one schema is read from JSON and written back: its Dart type, its decoder, and the expression that gives the JSON form. */
interface Codec {
  type: string;
  decoder: string;
  /** Null when the Dart value already is the JSON value. */
  encode: ((expression: string, depth: number) => string) | null;
  /** The same for a value known not to be null (the type may allow null; an optional member is written only when it is there). */
  bare: ((expression: string, depth: number) => string) | null;
}

interface Shape {
  name: string;
  schema: Node;
}

class ResponseGenerator {
  private readonly shapes = new Map<string, Shape>();
  private readonly pending: string[] = [];
  private readonly schemas: Record<string, Node>;

  constructor(schemas: Record<string, Node>) {
    this.schemas = schemas;
  }

  /** The class for an object schema, registered once under its name; two different schemas under one name are an error. */
  private shape(name: string, schema: Node): string {
    const known = this.shapes.get(name);
    if (known === undefined) {
      this.shapes.set(name, { name, schema });
      this.pending.push(name);
    } else if (known.schema !== schema) {
      throw new Error(`two response classes would be named ${name}`);
    }
    return name;
  }

  codec(schema: Node, owner: string, field: string): Codec {
    const ref = typeof schema.$ref === 'string' && schema.$ref.startsWith(REF_PREFIX) ? schema.$ref.slice(REF_PREFIX.length) : undefined;
    if (ref !== undefined) {
      const target = this.schemas[ref];
      if (target === undefined) throw new Error(`response schema ${ref} is missing`);
      const flat = flatten(target, this.schemas);
      const kind = kindOf(flat);
      const nullable = kind.nullable || schema.nullable === true;
      if (kind.type === 'object' && this.hasProperties(flat)) return this.wrap(this.model(`${pascal(ref)}Response`, target), nullable);
      return this.wrap(this.plain(flat, `${pascal(ref)}Response`, '', kind), nullable);
    }
    const flat = flatten(schema, this.schemas);
    const kind = kindOf(flat);
    if (kind.type === 'object' && this.hasProperties(flat)) return this.wrap(this.model(`${owner}${pascal(field)}`, schema), kind.nullable);
    return this.wrap(this.plain(flat, owner, field, kind), kind.nullable);
  }

  private hasProperties(schema: Node): boolean {
    return Object.keys(asNode(schema.properties) ?? {}).length > 0;
  }

  private model(name: string, schema: Node): Codec {
    this.shape(name, schema);
    const encode = (expression: string): string => `${expression}.toJson()`;
    return { type: name, decoder: `${name}.fromJson`, encode, bare: encode };
  }

  private plain(schema: Node, owner: string, field: string, kind: Kind): Codec {
    switch (kind.type) {
      case 'string':
        return { type: 'String', decoder: 'asString', encode: null, bare: null };
      case 'integer':
        return { type: 'int', decoder: 'asInt', encode: null, bare: null };
      case 'number':
        return { type: 'num', decoder: 'asNum', encode: null, bare: null };
      case 'boolean':
        return { type: 'bool', decoder: 'asBool', encode: null, bare: null };
      case 'array': {
        const items = asNode(schema.items);
        if (items === undefined) return { type: 'List<Object?>', decoder: 'asList(asAny)', encode: null, bare: null };
        const inner = this.codec(items, owner, `${field}Item`);
        const encode = inner.encode;
        const written = encode === null ? null : (expression: string, depth: number): string => `${expression}.map((e${depth}) => ${encode(`e${depth}`, depth + 1)}).toList()`;
        return { type: `List<${inner.type}>`, decoder: `asList(${inner.decoder})`, encode: written, bare: written };
      }
      case 'object': {
        const additional = asNode(schema.additionalProperties);
        if (additional === undefined) return { type: 'Map<String, Object?>', decoder: 'asObject', encode: null, bare: null };
        const inner = this.codec(additional, owner, `${field}Value`);
        const encode = inner.encode;
        const written = encode === null ? null : (expression: string, depth: number): string => `<String, Object?>{for (final entry${depth} in ${expression}.entries) entry${depth}.key: ${encode(`entry${depth}.value`, depth + 1)}}`;
        return { type: `Map<String, ${inner.type}>`, decoder: `asMap(${inner.decoder})`, encode: written, bare: written };
      }
      default:
        return { type: 'Object?', decoder: 'asAny', encode: null, bare: null };
    }
  }

  private wrap(inner: Codec, nullable: boolean): Codec {
    if (!nullable || inner.type.endsWith('?')) return inner;
    const encode = inner.encode;
    return {
      type: `${inner.type}?`,
      decoder: `nullable(${inner.decoder})`,
      encode: encode === null ? null : (expression, depth) => `(${expression} == null ? null : ${encode(`${expression}!`, depth)})`,
      bare: encode,
    };
  }

  /** The classes of every shape met so far and of the shapes they contain, sorted by name. */
  render(): string[] {
    const rendered = new Map<string, string>();
    while (this.pending.length > 0) {
      const name = this.pending.shift() as string;
      rendered.set(name, this.renderShape(this.shapes.get(name) as Shape));
    }
    return [...rendered.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([, text]) => text);
  }

  private renderShape(shape: Shape): string {
    const schema = flatten(shape.schema, this.schemas);
    const properties = Object.entries(asNode(schema.properties) ?? {}).map(([wire, property]) => [wire, asNode(property) ?? {}] as [string, Node]);
    const required = new Set(Array.isArray(schema.required) ? schema.required.map(String) : []);
    const strict = schema.additionalProperties === false;
    const used = new Map<string, string>();
    const fields = properties.map(([wire, property]) => {
      const name = safe(camel(wire));
      const clash = used.get(name);
      if (clash !== undefined) throw new Error(`${shape.name}: properties ${clash} and ${wire} would both be named ${name}`);
      used.set(name, wire);
      const codec = this.codec(property, shape.name, wire);
      const isRequired = required.has(wire);
      return { wire, name, codec, isRequired, type: isRequired || codec.type.endsWith('?') ? codec.type : `${codec.type}?` };
    });
    const ordered = [...fields.filter((field) => field.isRequired), ...fields.filter((field) => !field.isRequired)];
    const known = `<String>{${fields.map((field) => quote(field.wire)).join(', ')}}`;
    const json = (field: (typeof fields)[number]): string => {
      const encode = field.isRequired ? field.codec.encode : field.codec.bare;
      const value = encode === null ? field.name : encode(field.isRequired ? field.name : `${field.name}!`, 0);
      return field.isRequired ? `        ${quote(field.wire)}: ${value},` : `        if (${field.name} != null) ${quote(field.wire)}: ${value},`;
    };
    return [
      `final class ${shape.name} implements ResponseModel {`,
      `  const ${shape.name}({`,
      ...ordered.map((field) => `    ${field.isRequired ? 'required ' : ''}this.${field.name},`),
      '    this.extra = const <String, Object?>{},',
      '  });',
      '',
      `  factory ${shape.name}.fromJson(Object? json, [String path = ${quote(shape.name)}]) {`,
      '    final Map<String, Object?> map = asObject(json, path);',
      `    return ${shape.name}(`,
      ...fields.map((field) =>
        field.isRequired
          ? `      ${field.name}: requiredField(map, path, ${quote(field.wire)}, ${field.codec.decoder}),`
          : `      ${field.name}: optionalField(map, path, ${quote(field.wire)}, ${field.codec.decoder}),`,
      ),
      `      extra: unknownFields(map, path, const ${known}, strict: ${strict}),`,
      '    );',
      '  }',
      '',
      ...fields.map((field) => `  final ${field.type} ${field.name};`),
      '',
      '  /// The members the contract does not name (kept so that writing the response back gives what was read).',
      '  final Map<String, Object?> extra;',
      '',
      '  @override',
      '  Map<String, Object?> toJson() => <String, Object?>{',
      ...fields.map(json),
      '        ...extra,',
      '      };',
      '}',
      '',
    ].join('\n');
  }
}

/** The schema of the first 2xx JSON response of an operation. */
function responseSchemaOf(operation: Node): Node | undefined {
  const responses = asNode(operation.responses) ?? {};
  const code = Object.keys(responses).sort().find((key) => /^2\d\d$/.test(key));
  if (code === undefined) return undefined;
  return asNode(asNode(asNode(asNode(responses[code])?.content)?.['application/json'])?.schema);
}

/** A response that satisfies the schema: every member, in the order the schema names them, with the simplest value of its type. Deterministic. */
function sampleOf(schema: Node, schemas: Record<string, Node>, depth: number): unknown {
  const ref = typeof schema.$ref === 'string' && schema.$ref.startsWith(REF_PREFIX) ? schema.$ref.slice(REF_PREFIX.length) : undefined;
  if (ref !== undefined) return sampleOf(schemas[ref] ?? {}, schemas, depth + 1);
  const flat = flatten(schema, schemas);
  if (Array.isArray(flat.enum) && flat.enum.length > 0) return flat.enum[0];
  if (flat.const !== undefined) return flat.const;
  const alternative = Array.isArray(flat.oneOf) ? flat.oneOf : Array.isArray(flat.anyOf) ? flat.anyOf : undefined;
  if (alternative !== undefined && alternative.length > 0) return sampleOf(asNode(alternative[0]) ?? {}, schemas, depth + 1);
  const kind = kindOf(flat);
  switch (kind.type) {
    case 'string': {
      const format = flat.format;
      if (format === 'uuid') return SAMPLE_UUID;
      if (format === 'date-time') return '2026-01-01T00:00:00Z';
      if (format === 'date') return '2026-01-01';
      if (format === 'uri') return 'https://example.test/sample';
      if (format === 'email') return 'sample@example.test';
      const minimum = typeof flat.minLength === 'number' ? flat.minLength : 0;
      const maximum = typeof flat.maxLength === 'number' ? flat.maxLength : Number.POSITIVE_INFINITY;
      return 'sample'.padEnd(minimum, 'x').slice(0, Math.max(maximum, 0));
    }
    case 'integer':
    case 'number':
      return typeof flat.minimum === 'number' ? Math.ceil(flat.minimum) : 1;
    case 'boolean':
      return true;
    case 'array': {
      if (depth > SAMPLE_DEPTH) return [];
      const items = asNode(flat.items);
      return items === undefined ? [] : [sampleOf(items, schemas, depth + 1)];
    }
    case 'object': {
      const properties = asNode(flat.properties);
      if (properties === undefined) {
        const additional = asNode(flat.additionalProperties);
        return additional === undefined || depth > SAMPLE_DEPTH ? {} : { key: sampleOf(additional, schemas, depth + 1) };
      }
      const required = new Set(Array.isArray(flat.required) ? flat.required.map(String) : []);
      const sample: Record<string, unknown> = {};
      for (const [wire, property] of Object.entries(properties)) {
        if (depth > SAMPLE_DEPTH && !required.has(wire)) continue;
        sample[wire] = sampleOf(asNode(property) ?? {}, schemas, depth + 1);
      }
      return sample;
    }
    default:
      return {};
  }
}

/**
 * Dart sources for the responses of the mobile client: a class for every response shape that reads the JSON strictly (a member the contract requires and the response lacks is
 * a mismatch that names it) and writes it back unchanged, a decoder for each operation, and one sample response for each operation for the contract test to read back.
 * `taken` are the names of the request classes, which a response class must not reuse.
 */
export function generateDartResponses(doc: OpenApiDocument, taken: ReadonlySet<string>): DartResponses {
  const schemas = Object.fromEntries(Object.entries(doc.components?.schemas ?? {}).map(([name, schema]) => [name, asNode(schema) ?? {}]));
  const generator = new ResponseGenerator(schemas);
  const decoders: Array<[string, string]> = [];
  const fixtures: Record<string, unknown> = {};
  const entries = listOperations(doc).filter((entry) => entry.operation.operationId !== undefined).sort((a, b) => a.id.localeCompare(b.id));
  for (const { id, operation } of entries) {
    const schema = responseSchemaOf(operation);
    if (schema === undefined) continue;
    const codec = generator.codec(schema, `${pascal(id)}Response`, '');
    decoders.push([id, codec.decoder]);
    fixtures[id] = sampleOf(schema, schemas, 0);
  }
  const classes = generator.render();
  for (const text of classes) {
    const name = /^final class (\w+)/.exec(text)?.[1] ?? '';
    if (taken.has(name)) throw new Error(`a response class would reuse the request class ${name}`);
  }
  const responses = [
    BANNER,
    "import 'response_model.dart';",
    '',
    '/// How to read the response of each operation that answers with JSON; throws a [ContractMismatch] naming the member that does not match the contract.',
    'final Map<String, Decoder<Object?>> responseDecoders = <String, Decoder<Object?>>{',
    ...decoders.map(([id, decoder]) => `  ${quote(id)}: ${decoder},`),
    '};',
    '',
    ...classes,
  ].join('\n');
  const fixtureText = `{\n${Object.entries(fixtures).map(([id, sample]) => `  ${JSON.stringify(id)}: ${JSON.stringify(sample)}`).join(',\n')}\n}\n`;
  return { responses, fixtures: fixtureText };
}
