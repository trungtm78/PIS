import { parseHexColor } from './contrast.ts';
import { DESIGN_TOKENS_PATH } from './generate.ts';
import type { DesignTokens, MobileV2Shadow, MobileV2Tokens, MobileV2TypeStep } from './types.ts';

export const DART_V2_OUTPUT_PATH = 'packages/mobile-tokens/lib/machvon_v2.generated.dart';

const GENERATED_NOTICE = `Generated by packages/design-tokens/src/mobile-v2.ts from ${DESIGN_TOKENS_PATH} (group mobileV2). Do not edit; run \`npm run dart:generate\`.`;
const DART_IDENTIFIER = /^[a-z][A-Za-z0-9]*$/;
const ALLOWED_WEIGHTS = [400, 600];
/** From this size on a line height of 1.25 is enough: the marks of large type take proportionally less room. */
const LARGE_TYPE = 28;

function identifier(name: string): string {
  if (!DART_IDENTIFIER.test(name)) throw new Error(`design tokens: mobileV2 ${name} is not usable as a Dart name`);
  return name;
}

function numeric(name: string, value: unknown): string {
  if (typeof value !== 'number' || !Number.isFinite(value)) throw new Error(`design tokens: mobileV2 ${name} is not a number`);
  return String(value);
}

function hexDigits(name: string, value: string | undefined): string {
  if (value === undefined) throw new Error(`design tokens: mobileV2 colour ${name} is missing`);
  try {
    parseHexColor(value);
  } catch {
    throw new Error(`design tokens: mobileV2 colour ${name} is not a hex value`);
  }
  if (value.length !== 7) throw new Error(`design tokens: mobileV2 colour ${name} is not a six digit hex value`);
  return value.slice(1).toUpperCase();
}

/** `#102E3B` to `Color(0xFF102E3B)`. */
function colorLiteral(name: string, value: string | undefined): string {
  return `Color(0xFF${hexDigits(name, value)})`;
}

/** `#102E3B` at 8% to `Color(0x14102E3B)`. */
function shadowColor(name: string, value: string, opacity: number): string {
  if (!(opacity >= 0 && opacity <= 1)) throw new Error(`design tokens: mobileV2 ${name} opacity is outside 0 to 1`);
  const alpha = Math.round(opacity * 255).toString(16).toUpperCase().padStart(2, '0');
  return `Color(0x${alpha}${hexDigits(name, value)})`;
}

function typeStep(name: string, step: MobileV2TypeStep): string {
  if (!ALLOWED_WEIGHTS.includes(step.weight)) throw new Error(`design tokens: mobileV2 type ${name} uses weight ${step.weight}; only 400 and 600 exist`);
  const minimumRatio = step.size >= LARGE_TYPE ? 1.25 : 1.33;
  if (step.line < step.size * minimumRatio - 0.001) throw new Error(`design tokens: mobileV2 type ${name} has a line height under ${minimumRatio} of its size (Vietnamese marks need room)`);
  return `MachvonV2TypeStep(size: ${numeric(`${name}.size`, step.size)}, line: ${numeric(`${name}.line`, step.line)}, weight: FontWeight.w${step.weight})`;
}

function shadowList(name: string, layers: MobileV2Shadow[]): string {
  if (layers.length === 0) return '<BoxShadow>[]';
  const items = layers.map(
    (layer) =>
      `BoxShadow(color: ${shadowColor(name, layer.color, layer.opacity)}, offset: Offset(${numeric(`${name}.dx`, layer.dx)}, ${numeric(`${name}.dy`, layer.dy)}), blurRadius: ${numeric(`${name}.blur`, layer.blur)}, spreadRadius: ${numeric(`${name}.spread`, layer.spread)})`,
  );
  return `<BoxShadow>[${items.join(', ')}]`;
}

function requireV2(json: DesignTokens): MobileV2Tokens {
  if (json.mobileV2 === undefined) throw new Error('design tokens: the mobileV2 group is missing');
  return json.mobileV2;
}

/**
 * Pure and deterministic: the Dart source of the mobile.v2 tokens (colours of both modes, the type scale, spacing, radii,
 * elevation, motion and sizes) from the one design token file. Only the phone gets this code; the web outputs never carry it.
 */
export function generateMobileV2Dart(json: DesignTokens): string {
  const v2 = requireV2(json);
  const keys = Object.keys(v2.color.light);
  const darkKeys = Object.keys(v2.color.dark);
  if (keys.join(',') !== darkKeys.join(',')) throw new Error('design tokens: mobileV2 light and dark colours must have the same keys in the same order');

  const lines: string[] = [`// ${GENERATED_NOTICE}`, "import 'package:flutter/material.dart';", ''];

  lines.push('/// The colours of one mode (light or dark) of the phone design.', '@immutable', 'class MachvonV2Palette {', '  const MachvonV2Palette({');
  for (const key of keys) lines.push(`    required this.${identifier(key)},`);
  lines.push('  });', '');
  for (const key of keys) lines.push(`  final Color ${key};`);
  lines.push('}', '');

  lines.push('/// The palettes of the phone design: `light` and `dark`.', 'abstract final class MachvonV2Colors {');
  for (const mode of ['light', 'dark'] as const) {
    lines.push(`  static const MachvonV2Palette ${mode} = MachvonV2Palette(`);
    for (const key of keys) lines.push(`    ${key}: ${colorLiteral(`${mode}.${key}`, v2.color[mode][key])},`);
    lines.push('  );');
  }
  lines.push('}', '');

  lines.push(
    '/// One step of the type scale: the size and the line height in logical pixels and the weight (400 or 600).',
    '@immutable',
    'class MachvonV2TypeStep {',
    '  const MachvonV2TypeStep({required this.size, required this.line, required this.weight});',
    '',
    '  final double size;',
    '  final double line;',
    '  final FontWeight weight;',
    '',
    '  /// The line height as a multiple of the size, as `TextStyle.height` wants it.',
    '  double get height => line / size;',
    '}',
    '',
  );

  lines.push('/// The type scale of the phone: six steps and two emphasised variants, two weights, line heights of at least 1.33 (1.25 from size 28).', 'abstract final class MachvonV2Type {');
  for (const [name, step] of Object.entries(v2.type.scale)) lines.push(`  static const MachvonV2TypeStep ${identifier(name)} = ${typeStep(name, step)};`);
  for (const [name, step] of Object.entries(v2.type.emphasis)) lines.push(`  static const MachvonV2TypeStep ${identifier(name)} = ${typeStep(name, step)};`);
  lines.push('');
  for (const [name, cap] of Object.entries(v2.type.scaleCap)) lines.push(`  /// The largest system text scale ${name} follows.`, `  static const double ${identifier(name)}ScaleCap = ${numeric(`scaleCap.${name}`, cap)};`);
  lines.push(`  /// From this text scale on, line clamps are lifted so no key text is cut.`, `  static const double clampFreeFrom = ${numeric('clampFreeFrom', v2.type.clampFreeFrom)};`, '}', '');

  lines.push('/// Spacing steps in logical pixels.', 'abstract final class MachvonV2Space {');
  for (const step of v2.space) lines.push(`  static const double s${numeric('space', step)} = ${numeric('space', step)};`);
  lines.push('}', '');

  lines.push('/// Corner radii in logical pixels.', 'abstract final class MachvonV2Radius {');
  for (const [name, value] of Object.entries(v2.radius)) lines.push(`  static const double ${identifier(name)} = ${numeric(`radius.${name}`, value)};`);
  lines.push('}', '');

  lines.push('/// Elevation: `e1` is a hairline lift, `e2` is the upward shadow of the action bar, the sheet and the floating button. Dark mode uses a border instead of a shadow.', 'abstract final class MachvonV2Elevation {');
  for (const [name, layers] of Object.entries(v2.elevation)) {
    lines.push(`  static const List<BoxShadow> ${identifier(name)}Light = ${shadowList(name, layers.light)};`);
    lines.push(`  static const List<BoxShadow> ${identifier(name)}Dark = ${shadowList(name, layers.dark)};`);
  }
  lines.push('}', '');

  const motion = v2.motion;
  if (motion.curve.length !== 4) throw new Error('design tokens: mobileV2 motion.curve needs four numbers');
  lines.push(
    '/// Motion: 150 to 250 ms, transform and opacity only; reduced motion keeps a short fade.',
    'abstract final class MachvonV2Motion {',
    `  static const Duration fast = Duration(milliseconds: ${numeric('motion.fastMs', motion.fastMs)});`,
    `  static const Duration slow = Duration(milliseconds: ${numeric('motion.slowMs', motion.slowMs)});`,
    `  static const Duration reduced = Duration(milliseconds: ${numeric('motion.reducedMs', motion.reducedMs)});`,
    `  static const Curve curve = Cubic(${motion.curve.map((value, index) => numeric(`motion.curve.${index}`, value)).join(', ')});`,
    `  static const double scrimOpacity = ${numeric('motion.scrimOpacity', motion.scrimOpacity)};`,
    '}',
    '',
  );

  lines.push('/// Fixed sizes of the phone design in logical pixels.', 'abstract final class MachvonV2Size {');
  for (const [name, value] of Object.entries(v2.size)) lines.push(`  static const double ${identifier(name)} = ${numeric(`size.${name}`, value)};`);
  lines.push('}', '');
  return lines.join('\n');
}
