// Generates lib/features/registry.generated.dart: the list of the features found under lib/features.
//
// A feature is a file lib/features/<name>/<name>_feature.dart that declares a top-level `feature` of type
// MobileFeature. The list is derived from the directory, so a story adds a feature by adding that file and running
//
//   dart run tool/generate_registry.dart           writes the file
//   dart run tool/generate_registry.dart --check   fails when the file does not match the directories
import 'dart:io';

const String featuresDirectory = 'lib/features';
const String generatedRegistryFile = '$featuresDirectory/registry.generated.dart';
final RegExp _featureName = RegExp(r'^[a-z][a-z0-9_]*$');

/// The text of the generated file for the feature names (directory names), in the order given.
String renderRegistry(List<String> names) {
  final List<String> sorted = List<String>.of(names)..sort();
  final StringBuffer out = StringBuffer()
    ..writeln('// Generated by tool/generate_registry.dart from the directories of lib/features. Do not edit; run `dart run tool/generate_registry.dart`.');
  out.writeln("import '../core/navigation/feature.dart';");
  for (final String name in sorted) {
    out.writeln("import '$name/${name}_feature.dart' as f_$name;");
  }
  out
    ..writeln()
    ..writeln('/// Every feature of the application; the router, the string tables and the registry tests read this list.')
    ..writeln('final List<MobileFeature> kAllFeatures = <MobileFeature>[');
  for (final String name in sorted) {
    out.writeln('  f_$name.feature,');
  }
  out.writeln('];');
  return out.toString();
}

/// The names of the feature directories: those that hold `<name>/<name>_feature.dart`.
List<String> discoverFeatures() {
  final List<String> names = <String>[];
  for (final FileSystemEntity entity in Directory(featuresDirectory).listSync()) {
    if (entity is! Directory) continue;
    final String name = entity.uri.pathSegments.where((String segment) => segment.isNotEmpty).last;
    if (!_featureName.hasMatch(name)) throw StateError('feature directory "$name" must be lower_snake_case');
    if (File('${entity.path}/${name}_feature.dart').existsSync()) names.add(name);
  }
  return names;
}

void main(List<String> arguments) {
  final String expected = renderRegistry(discoverFeatures());
  final File target = File(generatedRegistryFile);
  if (arguments.contains('--check')) {
    if (!target.existsSync() || _lf(target.readAsStringSync()) != expected) {
      stderr.writeln('$generatedRegistryFile is out of date; run `dart run tool/generate_registry.dart`.');
      exitCode = 1;
    }
    return;
  }
  target.writeAsStringSync(expected);
}

/// A checkout with core.autocrlf (Windows) reads the generated file with CRLF; the generator writes LF.
String _lf(String text) => text.replaceAll('\r\n', '\n');
