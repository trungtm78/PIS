// Writes the launcher icons, the splash logo and the in-app logo images of the phone application from the master mark of the brand
// (apps/web/src/pwa/icon-art.ts, colours in apps/web/src/brand/palettes.ts). Nothing here is a Flutter package: the PNGs are rendered with
// the Playwright of the repository, the Android adaptive icon is a vector drawable.
// Usage: node --disable-warning=ExperimentalWarning apps/mobile/tool/generate_launcher_icons.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PNG } from 'pngjs';
import { MARK_PALETTES } from '../../web/src/brand/palettes.ts';
import { MARK, iconSvg } from '../../web/src/pwa/icon-art.ts';

const mobile = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const res = join(mobile, 'android', 'app', 'src', 'main', 'res');
const ios = join(mobile, 'ios', 'Runner', 'Assets.xcassets');
const assets = join(mobile, 'assets', 'brand');
const pub = MARK_PALETTES.public.mark;
const ent = MARK_PALETTES.enterprise.mark;

const jobs = [];
const queue = (path, svg, size, opaque = false) => {
  mkdirSync(dirname(path), { recursive: true });
  jobs.push({ path, svg, size, opaque });
};
const write = (path, text) => {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, text);
};

// Android legacy launcher icons (the rounded tile) for the launchers that know no adaptive icon.
for (const [density, size] of Object.entries({ mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 })) {
  queue(join(res, `mipmap-${density}`, 'ic_launcher.png'), iconSvg(pub), size);
}
// The splash logo of Android (drawable/launch_logo.png) and of iOS (LaunchImage).
queue(join(res, 'drawable', 'launch_logo.png'), iconSvg(pub), 288);
for (const [file, size] of Object.entries({ 'LaunchImage.png': 168, 'LaunchImage@2x.png': 336, 'LaunchImage@3x.png': 504 })) {
  queue(join(ios, 'LaunchImage.imageset', file), iconSvg(pub), size);
}
// iOS app icons: square and opaque (the system rounds them), one file per entry of Contents.json.
const contents = JSON.parse(readFileSync(join(ios, 'AppIcon.appiconset', 'Contents.json'), 'utf8'));
for (const image of contents.images) {
  const px = Math.round(parseFloat(image.size) * parseInt(image.scale, 10));
  queue(join(ios, 'AppIcon.appiconset', image.filename), iconSvg(pub, { maskable: true }), px, true);
}
// The in-app logo of each edition (sign-in screen) and the store icons of both.
queue(join(assets, 'logo-public.png'), iconSvg(pub), 384);
queue(join(assets, 'logo-enterprise.png'), iconSvg(ent), 384);
queue(join(assets, 'launcher-public-1024.png'), iconSvg(pub, { maskable: true }), 1024, true);
queue(join(assets, 'launcher-enterprise-1024.png'), iconSvg(ent, { maskable: true }), 1024, true);

/** Path data of a rounded rectangle (arcs) or a polygon, in the 512 unit canvas of the mark. */
function pathOf(shape) {
  if (shape.points !== undefined) return `M${shape.points.map(([x, y]) => `${Math.round(x * 100) / 100},${Math.round(y * 100) / 100}`).join(' L')} Z`;
  const { x, y, width: w, height: h, radius: r } = shape;
  return `M${x + r},${y} h${w - 2 * r} a${r},${r} 0 0 1 ${r},${r} v${h - 2 * r} a${r},${r} 0 0 1 -${r},${r} h-${w - 2 * r} a${r},${r} 0 0 1 -${r},-${r} v-${h - 2 * r} a${r},${r} 0 0 1 ${r},-${r} Z`;
}

const vector = (fillOf, scale) =>
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tool/generate_launcher_icons.mjs from the master mark of the brand; do not edit. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp"\n    android:height="108dp"\n    android:viewportWidth="512"\n    android:viewportHeight="512">\n    <group android:pivotX="256" android:pivotY="256" android:scaleX="${scale}" android:scaleY="${scale}">\n${MARK.map((shape) => `        <path android:fillColor="${fillOf(shape.fill)}" android:pathData="${pathOf(shape)}"/>`).join('\n')}\n    </group>\n</vector>\n`;

// The adaptive icon: the mark sits inside the 66 dp safe circle of the 108 dp canvas.
write(join(res, 'drawable', 'ic_launcher_foreground.xml'), vector((fill) => pub[fill], 0.76));
write(join(res, 'drawable', 'ic_launcher_monochrome.xml'), vector(() => '#FFFFFFFF', 0.76));
write(join(res, 'values', 'ic_launcher_background.xml'), `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_background">${pub.background}</color>\n</resources>\n`);
write(
  join(res, 'mipmap-anydpi-v26', 'ic_launcher.xml'),
  `<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n    <background android:drawable="@color/ic_launcher_background"/>\n    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n</adaptive-icon>\n`,
);
// The enterprise edition (a build made with --dart-define=MACHVON_EDITION=enterprise): the same files with the mark of the enterprise palette, in
// android/app/src/enterprise/res, which android/app/build.gradle.kts puts over the main resources only for such a build. The strings of the
// application name are written by hand there (values/strings.xml); this tool does not touch them.
const entRes = join(mobile, 'android', 'app', 'src', 'enterprise', 'res');
for (const [density, size] of Object.entries({ mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 })) {
  queue(join(entRes, `mipmap-${density}`, 'ic_launcher.png'), iconSvg(ent), size);
}
queue(join(entRes, 'drawable', 'launch_logo.png'), iconSvg(ent), 288);
write(join(entRes, 'drawable', 'ic_launcher_foreground.xml'), vector((fill) => ent[fill], 0.76));
write(join(entRes, 'values', 'ic_launcher_background.xml'), `<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">${ent.background}</color>
</resources>
`);
// The splash: white page with the logo in the middle (the first frame of Flutter is of the same kind).
const splash = `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tool/generate_launcher_icons.mjs: the logo of the brand on the page of the first frame. -->\n<layer-list xmlns:android="http://schemas.android.com/apk/res/android">\n    <item android:drawable="@android:color/white" />\n    <item>\n        <bitmap\n            android:gravity="center"\n            android:src="@drawable/launch_logo" />\n    </item>\n</layer-list>\n`;
write(join(res, 'drawable', 'launch_background.xml'), splash);
write(join(res, 'drawable-v21', 'launch_background.xml'), splash);

const { chromium } = await import('playwright');
const browser = await chromium.launch();
try {
  for (const job of jobs) {
    const page = await browser.newPage({ viewport: { width: 512, height: 512 }, deviceScaleFactor: job.size / 512 });
    await page.setContent(`<!doctype html><html><body style="margin:0;background:transparent">${job.svg.replace('<svg ', '<svg style="display:block" ')}</body></html>`);
    await page.screenshot({ path: job.path, omitBackground: true, clip: { x: 0, y: 0, width: 512, height: 512 } });
    await page.close();
    // The App Store refuses an icon with an alpha channel: write those as RGB.
    if (job.opaque) writeFileSync(job.path, PNG.sync.write(PNG.sync.read(readFileSync(job.path)), { colorType: 2, inputColorType: 6, inputHasAlpha: true }));
  }
} finally {
  await browser.close();
}
process.stdout.write(`launcher icons: ${jobs.length} images\n`);
