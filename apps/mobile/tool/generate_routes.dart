// Generates lib/core/navigation/mobile_routes.generated.dart from the mobile part of the navigation architecture.
//
//   dart run tool/generate_routes.dart           writes the file
//   dart run tool/generate_routes.dart --check   fails when the file is not what the design files produce
import 'dart:convert';
import 'dart:io';

const String _navigationFile = '../../Design/MACHVON_Design/03_Engineering/navigation_architecture.json';
const String _catalogueFile = '../../Design/MACHVON_Design/03_Engineering/screen_catalog.json';
const String generatedRoutesFile = 'lib/core/navigation/mobile_routes.generated.dart';

/// The text of the generated file for the given design files.
String renderRoutes({required String navigationJson, required String catalogueJson}) {
  final Map<String, Object?> navigation = jsonDecode(navigationJson) as Map<String, Object?>;
  final List<Object?> catalogue = jsonDecode(catalogueJson) as List<Object?>;
  final Map<String, String> requirementById = <String, String>{
    for (final Object? entry in catalogue)
      (entry! as Map<String, Object?>)['id']! as String: (entry as Map<String, Object?>)['req']! as String,
  };
  final StringBuffer out = StringBuffer()
    ..writeln('// Generated by tool/generate_routes.dart from navigation_architecture.json and screen_catalog.json. Do not edit; run `dart run tool/generate_routes.dart`.')
    ..writeln("import 'route_catalogue.dart';")
    ..writeln()
    ..writeln('/// Every screen of the mobile navigation architecture.')
    ..writeln('const List<MobileRoute> kMobileRoutes = <MobileRoute>[');
  for (final Object? entry in navigation['mobileRoutes']! as List<Object?>) {
    final Map<String, Object?> route = entry! as Map<String, Object?>;
    final String id = route['id']! as String;
    final String? requirement = requirementById[id];
    if (requirement == null) throw StateError('$id is a mobile route without an entry in screen_catalog.json');
    final Object? tab = route['bottomNavigation'];
    out.write("  MobileRoute(id: '$id', kind: '${route['kind']}', requirement: '$requirement'");
    if (tab != null) out.write(', tab: AppTab.$tab');
    if (tab != null && route['tabRoot'] == id) out.write(', isTabRoot: true');
    out.writeln('),');
  }
  out.writeln('];');
  return out.toString();
}

/// The text the generated file must have, read from the design files; relative paths are from apps/mobile.
String expectedRoutes() => renderRoutes(
      navigationJson: File(_navigationFile).readAsStringSync(),
      catalogueJson: File(_catalogueFile).readAsStringSync(),
    );

void main(List<String> arguments) {
  final String expected = expectedRoutes();
  final File target = File(generatedRoutesFile);
  if (arguments.contains('--check')) {
    if (!target.existsSync() || target.readAsStringSync() != expected) {
      stderr.writeln('$generatedRoutesFile is out of date; run `dart run tool/generate_routes.dart`.');
      exitCode = 1;
    }
    return;
  }
  target.writeAsStringSync(expected);
}
