import { editionOf } from './edition-terms.ts';

/**
 * The folder (inside apps/web/e2e) that holds the baseline PNGs of the visual cases for one operating system.
 *
 * A baseline is rendered pixels and every OS draws text its own way (Windows with sub-pixel LCD anti-aliasing, Linux with grayscale FreeType hinting), so a region that
 * contains text cannot match a baseline made on another OS within the 0.1 percent target. The committed set `visual-baselines` was rendered by Google Chrome on Windows
 * and is compared on Windows only. Another OS has a folder of its own, `visual-baselines-<platform>` (for example `visual-baselines-linux`), generated by the browser
 * workflow on a hosted runner (`workflow_dispatch` with update_visual), reviewed like any baseline and committed. Until that folder exists the visual cases are skipped
 * there, with the reason in the Playwright output, and the route walk and the flows still run. `E2E_VISUAL_BASELINES` names the folder explicitly.
 *
 * A baseline is also the pixels of one edition: the enterprise edition has its own name, brand, home and terminology (its overlay), so its screens never match the baselines of the public edition. The committed
 * set is the public edition's. The enterprise edition has a folder of its own, `visual-baselines-enterprise` (`visual-baselines-enterprise-<platform>` on another OS), rendered and approved like any baseline
 * (docs/r10-baseline-approvals.md); until it exists the visual cases of an enterprise run are skipped, never compared with the public edition's pixels and never passed.
 */
export function baselinesFolder(platform: string = process.platform, env: Record<string, string | undefined> = process.env): string {
  const chosen = env.E2E_VISUAL_BASELINES;
  if (chosen !== undefined && chosen !== '') return chosen;
  const edition = editionOf(env) === 'enterprise' ? '-enterprise' : '';
  return platform === 'win32' ? `visual-baselines${edition}` : `visual-baselines${edition}-${platform}`;
}

/** What a skipped or failed visual gate says: which edition and which folder had no baselines. */
export function missingBaselinesReason(folder: string, edition: 'public' | 'enterprise'): string {
  return `no baselines of the ${edition} edition rendered on this OS (${folder}): see docs/runbooks/web-e2e.md, "Baselines of another OS" and "Baselines of the enterprise edition"`;
}

/**
 * What the visual cases do on this OS: `run` when baselines exist or are being rendered (E2E_UPDATE_VISUAL=1), otherwise `fail` when the visual cases are required
 * (E2E_REQUIRE_VISUAL=1: a gate that cannot compare is red, never silently green) and `skip` when they are optional.
 */
export function visualGate(state: { updating: boolean; required: boolean; baselinesExist: boolean }): 'run' | 'skip' | 'fail' {
  if (state.updating || state.baselinesExist) return 'run';
  return state.required ? 'fail' : 'skip';
}
