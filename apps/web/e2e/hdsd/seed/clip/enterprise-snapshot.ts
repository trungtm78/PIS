import type { Obj, SeedContext } from '../context.ts';
import { asObj } from '../context.ts';
import { clipPlan } from './plan.ts';
import TEXTS from '../data/enterprise-more.json' with { type: 'json' };

/**
 * Group `clip-ent-snapshot`: the enterprise period snapshot (ENT-3a) of the latest month whose deadline has passed, made with the commands of the product only.
 *
 *   1. the months of the enterprise calendar of the plan year are generated (`generateReportingPeriods`, calendar ENTERPRISE) once;
 *   2. the readiness of the chosen month (`getEnterpriseSnapshotReadiness`) names the cells (project, class, measure, months) whose actual has not been handed in; for each, the actuals of the months up to the
 *      chosen one are proposed by the officer and accepted by the leader (the year plan of the cell, read from the figure board, decides the size: the company is at a ratio of its plan, each project at its own);
 *   3. the month is soft closed and locked, the snapshot is built by the officer and frozen by the owner (two people, both over the whole tenant).
 *
 * Idempotent: a month that already has a frozen snapshot is left alone; a half way run is taken up at the step it stopped. The leader panel (HOME-09) and the funding structure (HOME-07) of the enterprise
 * edition read this snapshot, so the demo shows the rates against the annual plan by company, unit and project.
 */

const PREPARER = 'projectManager';
const APPROVER = 'capApprover';
const OWNER = 'owner';
const BUILDER = 'projectManager';
const FREEZER = 'owner';
const CALENDAR = 'ENTERPRISE';
const REASON = TEXTS['snapshotPeriod.reason'];
/** The most rounds of "ask what is missing, enter it": the first fills everything, the others take up a refusal half way. */
const ROUNDS = 3;
const BATCH_ENTRIES = 12;

export interface Missing {
  projectId: string;
  projectCode: string;
  classCode: string;
  tierCode: string;
  measure: string;
  months: number[];
}

/** How the actuals of a snapshot are paced: a salt on the key of a cell (another snapshot of the same projects gets other shares) and the percent of the plan the actuals are taken from. */
export interface ActualPace {
  salt: string;
  percent: number;
}
export const DEFAULT_PACE: ActualPace = { salt: '', percent: 100 };

/** A small stable number of a text (FNV-1a), so the same project always gets the same pace. */
export function hashOf(text: string): number {
  let hash = 2166136261;
  for (const char of text) {
    hash ^= char.codePointAt(0) ?? 0;
    hash = Math.imul(hash, 16777619) >>> 0;
  }
  return hash >>> 0;
}

/**
 * The monthly actuals of a cell up to `lastMonth`: the cumulative lands at a share of the year plan that belongs to the project (between 38 and 88 percent for a disbursement, a little more for the work done),
 * spread over the months with a mild wave. Whole dong; the months named in `months` only. A cell without a plan gets small even amounts (never a figure out of nothing).
 */
export function actualPlan(input: { key: string; measure: string; planVnd: string | null; lastMonth: number; months: readonly number[] }): Array<{ month: number; amountVnd: string }> {
  const seed = hashOf(input.key);
  const share = 38 + (seed % 51) + (input.measure === 'EXECUTED' ? 7 : 0);
  const weights = Array.from({ length: input.lastMonth }, (_, index) => 100 + ((seed >>> (index % 16)) % 40) - 20);
  const sum = weights.reduce((total, weight) => total + weight, 0);
  const plan = input.planVnd === null ? 0n : BigInt(input.planVnd);
  const target = (plan * BigInt(share)) / 100n;
  const MILLION = 1_000_000n;
  return input.months.map((month) => {
    const weight = BigInt(weights[month - 1] ?? 100);
    const raw = target === 0n ? 0n : (target * weight) / BigInt(sum);
    return { month, amountVnd: ((raw / MILLION) * MILLION).toString() };
  });
}

export const monthOf = (period: Obj): number => Number(String(period.end_date).slice(5, 7));

async function enterprisePeriods(ctx: SeedContext, planYear: number): Promise<Obj[]> {
  return ctx.list<Obj>(OWNER, '/resources/reporting_period', { calendar_code: CALENDAR, fiscal_year: planYear, period_type: 'MONTH' });
}

/** The months of the enterprise calendar of the year (generated by the command when there are none). */
export async function ensurePeriods(ctx: SeedContext, planYear: number): Promise<Obj[]> {
  const known = await enterprisePeriods(ctx, planYear);
  if (known.length > 0) return known;
  const generated = await ctx.attempt(OWNER, 'POST', '/reporting-periods/generate', { calendar_code: CALENDAR, fiscal_year: planYear, period_type: 'MONTH' });
  if (!generated.ok) return [];
  return enterprisePeriods(ctx, planYear);
}

/** The latest month whose deadline has passed: the one a company closes now. */
export function chosenPeriod(periods: readonly Obj[], now: Date): Obj | undefined {
  return [...periods].filter((period) => Date.parse(String(period.deadline_at)) < now.getTime()).sort((left, right) => String(right.start_date).localeCompare(String(left.start_date)))[0];
}

export function missingOf(readiness: Obj): Missing[] {
  const out: Missing[] = [];
  for (const unit of (readiness.missing_units as Obj[] | undefined) ?? []) {
    for (const project of (unit.projects as Obj[] | undefined) ?? []) {
      for (const cell of (project.cells as Obj[] | undefined) ?? []) {
        out.push({
          projectId: String(project.project_id),
          projectCode: String(project.project_code),
          classCode: String(cell.class_code),
          tierCode: String(cell.tier_code),
          measure: String(cell.measure),
          months: ((cell.months as number[] | undefined) ?? []).map(Number).sort((left, right) => left - right),
        });
      }
    }
  }
  return out;
}

/** The plan in force of every (project, class, measure) of the year, read from the figure board (one read per measure). */
async function plansOf(ctx: SeedContext, planYear: number, measures: readonly string[], ordinal: number): Promise<Map<string, string | null>> {
  const plans = new Map<string, string | null>();
  for (const measure of measures) {
    const board = await ctx.get<Obj>(OWNER, '/funding-figures/board', { plan_year: planYear, period_grain: 'MONTH', period_ordinal: ordinal, measure, limit: 200 });
    for (const project of (board.projects as Obj[] | undefined) ?? []) {
      for (const cell of (project.cells as Obj[] | undefined) ?? []) plans.set(`${String(project.project_id)}|${String(cell.class_code)}|${String(cell.tier_code)}|${measure}`, typeof cell.plan_in_force_vnd === 'string' ? cell.plan_in_force_vnd : null);
    }
  }
  return plans;
}

function scaled(planVnd: string | null, percent: number): string | null {
  return planVnd === null ? null : ((BigInt(planVnd) * BigInt(percent)) / 100n).toString();
}

export async function enterActuals(ctx: SeedContext, missing: readonly Missing[], planYear: number, lastMonth: number, pace: ActualPace = DEFAULT_PACE): Promise<number> {
  const plans = await plansOf(ctx, planYear, [...new Set(missing.map((cell) => cell.measure))], lastMonth);
  let handed = 0;
  for (const cell of missing) {
    if (cell.months.length === 0) continue;
    const entries = actualPlan({ key: `${cell.projectCode}:${cell.classCode}${pace.salt}`, measure: cell.measure, planVnd: scaled(plans.get(`${cell.projectId}|${cell.classCode}|${cell.tierCode}|${cell.measure}`) ?? null, pace.percent), lastMonth, months: cell.months });
    for (let from = 0; from < entries.length; from += BATCH_ENTRIES) {
      const slice = entries.slice(from, from + BATCH_ENTRIES);
      const proposed = await ctx.attempt<Obj>(PREPARER, 'POST', '/funding-figures/batches', {
        project_id: cell.projectId,
        class_code: cell.classCode,
        tier_code: cell.tierCode,
        measure: cell.measure,
        figure_kind: 'ACTUAL',
        period_grain: 'MONTH',
        plan_year: planYear,
        basis: 'REPORTED',
        as_of_date: ctx.day(-1),
        entries: slice.map((entry) => ({ period_ordinal: entry.month, amount_vnd: entry.amountVnd })),
      });
      if (!proposed.ok) continue;
      const sent = await ctx.attempt<Obj>(PREPARER, 'POST', `/funding-figures/batches/${String(proposed.json.resource_id)}/submission`, {}, { version: proposed.json.resource_version as number });
      if (!sent.ok) continue;
      const accepted = await ctx.attempt<Obj>(APPROVER, 'POST', `/funding-figures/batches/${String(proposed.json.resource_id)}/acceptance`, {}, { version: sent.json.resource_version as number });
      if (accepted.ok) handed += 1;
    }
  }
  return handed;
}

/** The month soft closed and locked by the commands of DIS (each step only when the month is at the state before it). */
export async function closeAndLock(ctx: SeedContext, period: Obj): Promise<boolean> {
  let current = period;
  for (let step = 0; step < 2; step += 1) {
    if (String(current.status) === 'LOCKED') return true;
    const action = String(current.status) === 'OPEN' ? 'soft-close' : 'lock';
    const moved = await ctx.attempt<Obj>(OWNER, 'POST', `/reporting-periods/${String(current.id)}/${action}`, { reason: REASON }, { version: Number(current.version) });
    if (!moved.ok) return false;
    current = await ctx.get<Obj>(OWNER, `/resources/reporting_period/${String(current.id)}`);
  }
  return String(current.status) === 'LOCKED';
}

export async function seedClipEnterpriseSnapshot(ctx: SeedContext): Promise<void> {
  const plan = clipPlan();
  if (plan === undefined || plan.dataset !== 'enterprise') {
    ctx.warn('no enterprise clip plan (CLIP_PLAN_FILE): the group has nothing to do');
    return;
  }
  const planYear = Number(plan.planYear);
  const periods = await ctx.step('DIS', `months of the enterprise calendar ${planYear}`, () => ensurePeriods(ctx, planYear));
  const period = chosenPeriod(periods, new Date());
  if (period === undefined) {
    ctx.warn(`no month of the enterprise calendar ${planYear} is past its deadline: no snapshot to make`);
    return;
  }
  await freezeMonth(ctx, period, planYear, DEFAULT_PACE);
}

/** Takes one month of the enterprise calendar to a frozen snapshot: the missing actuals handed in and accepted, the month locked, the snapshot built by the officer and frozen by the owner. Skips a month already frozen; false when a step was refused. */
export async function freezeMonth(ctx: SeedContext, period: Obj, planYear: number, pace: ActualPace): Promise<boolean> {
  const label = String(period.code);
  const known = await ctx.list<Obj>(OWNER, '/enterprise-snapshots', { period_id: String(period.id), limit: 50 });
  const frozen = known.find((row) => row.status === 'FROZEN');
  if (frozen !== undefined) {
    ctx.log(`  [snapshot] ${label} already frozen (revision ${String(frozen.revision)})`);
    return true;
  }
  const lastMonth = monthOf(period);
  await ctx.step('FND', `actuals up to ${label}`, async () => {
    for (let round = 0; round < ROUNDS; round += 1) {
      const readiness = await ctx.get<Obj>(OWNER, '/enterprise-snapshot-readiness', { period_id: String(period.id) });
      const missing = missingOf(readiness);
      if (readiness.complete === true || missing.length === 0) return;
      const handed = await enterActuals(ctx, missing, planYear, lastMonth, pace);
      ctx.log(`  [snapshot] round ${round + 1}: ${missing.length} cells missing, ${handed} batches accepted`);
      if (handed === 0) return;
    }
  });
  const fresh = await ctx.get<Obj>(OWNER, `/resources/reporting_period/${String(period.id)}`);
  if (!(await ctx.step('DIS', `lock ${label}`, () => closeAndLock(ctx, fresh)))) {
    ctx.warn(`the month ${label} could not be locked: no snapshot`);
    return false;
  }
  let snapshot = known.find((row) => row.status === 'BUILDING');
  if (snapshot === undefined) {
    const built = await ctx.attempt<Obj>(BUILDER, 'POST', '/enterprise-snapshots', { period_id: String(period.id) });
    if (!built.ok) {
      ctx.warn(`the snapshot of ${label} could not be built (readiness: ${JSON.stringify(asObj(built.json).code ?? built.status)})`);
      return false;
    }
    snapshot = { id: built.json.resource_id, version: built.json.resource_version, status: built.json.status };
  }
  const done = await ctx.attempt<Obj>(FREEZER, 'POST', `/enterprise-snapshots/${String(snapshot.id)}/freeze`, {}, { version: Number(snapshot.version) });
  if (!done.ok) {
    ctx.warn(`the snapshot of ${label} could not be frozen`);
    return false;
  }
  ctx.record({ module: 'DIS', screen: 'DIS-33', kind: 'enterprise-snapshot', id: String(snapshot.id), code: label, note: 'frozen' });
  return true;
}
