import type { Obj, SeedContext } from '../context.ts';
import { asObj } from '../context.ts';
import { clipPlan } from './plan.ts';
import { DEFAULT_PACE, ensurePeriods, freezeMonth, monthOf } from './enterprise-snapshot.ts';
import TEXTS from '../data/enterprise-crosscheck.json' with { type: 'json' };

/**
 * Group `clip-ent-crosscheck`: a deliberate, unexplained discrepancy between a monthly report and the frozen snapshot of the same period, so the cross-report check (RPT-09) has something to show. The period is
 * the fifth month of the plan year (2026-M05); the months the runbook uses for the HPM chain stay clean. Made with the commands of the product only:
 *
 *   1. the month is locked and its snapshot (revision 1) built and frozen (`freezeMonth`, as for the current month);
 *   2. the PVN monthly report of the month is drafted by the officer (from revision 1) and checked by the owner, and left there: the head of the committee approves and issues it live;
 *   3. a figure of the books is corrected afterwards: an actual of disbursement of a month of the PREVIOUS year (an open month; the frozen snapshots do not move) is reported again, a little higher;
 *   4. the owner asks to reopen the month, the leader approves (a second person), the officer builds revision 2 and the owner freezes it: it carries the corrected cumulative.
 *
 * The comparison then finds the cumulative disbursed since the start different between the report (revision 1) and the snapshot (revision 2): BLOCKING (XR-02), unexplained. The release of the draft is refused until the
 * head of the committee, who prepared none of the reports, explains the finding. Idempotent: what exists is left alone.
 */

const PREPARER = 'projectManager';
const CHECKER = 'owner';
const REQUESTER = 'owner';
const DECIDER = 'capApprover';
const BUILDER = 'projectManager';
const FREEZER = 'owner';
const LAYOUT = 'PVN-MONTHLY';
const MONTH = 5;
/** The month of the previous year whose actual is reported again, and the rise (billions of dong). */
const CORRECTED_MONTH = 3;
const RISE_VND = 2_000_000_000n;
const WINDOW_HOURS = 24;
const text = (key: keyof typeof TEXTS): string => TEXTS[key];

interface Block {
  planYear: number;
}

const periodCodeOf = (year: number): string => `${year}-M${String(MONTH).padStart(2, '0')}`;

async function draftOf(ctx: SeedContext, year: number): Promise<Obj | undefined> {
  const code = periodCodeOf(year);
  const drafts = await ctx.list<Obj>(PREPARER, '/report-engine/drafts');
  return drafts.find((row) => row.layout_code === LAYOUT && row.period_code === code);
}

/** The draft of the report: generated by the officer, checked by the owner. A draft or a copy that exists is left alone. */
async function draftReport(ctx: SeedContext, year: number): Promise<Obj | undefined> {
  const code = periodCodeOf(year);
  const issued = (await ctx.list<Obj>(PREPARER, '/report-engine/issues')).find((row) => row.layout_code === LAYOUT && row.period_code === code);
  if (issued !== undefined) return undefined;
  let draft = await draftOf(ctx, year);
  if (draft === undefined) {
    const made = await ctx.attempt<Obj>(PREPARER, 'POST', '/report-engine/drafts', { layout_code: LAYOUT, period: { kind: 'MONTH', year, index: MONTH } });
    if (!made.ok) {
      ctx.warn(`the report ${LAYOUT} ${code} could not be drafted (HTTP ${made.status})`);
      return undefined;
    }
    draft = await ctx.get<Obj>(PREPARER, `/report-engine/drafts/${String(made.json.draft_id ?? made.json.resource_id)}`);
  }
  if (String(draft.state) === 'DRAFT') {
    const checked = await ctx.attempt(CHECKER, 'POST', `/report-engine/drafts/${String(draft.id)}/check`, {}, { version: Number(draft.version) });
    if (!checked.ok) ctx.warn(`the draft ${LAYOUT} ${code} could not be checked (HTTP ${checked.status})`);
    draft = await ctx.get<Obj>(PREPARER, `/report-engine/drafts/${String(draft.id)}`);
  }
  return draft;
}

/** The first cell of the previous year that has an actual of disbursement in the corrected month: it is reported again, higher. */
async function correctBooks(ctx: SeedContext, priorYear: number): Promise<boolean> {
  const board = await ctx.get<Obj>(CHECKER, '/funding-figures/board', { plan_year: priorYear, period_grain: 'MONTH', period_ordinal: CORRECTED_MONTH, measure: 'DISBURSED', limit: 200 });
  for (const project of (board.projects as Obj[] | undefined) ?? []) {
    for (const cell of (project.cells as Obj[] | undefined) ?? []) {
      const actual = asObj(cell.actual);
      const amount = typeof actual.amount_vnd === 'string' ? actual.amount_vnd : typeof cell.actual_vnd === 'string' ? cell.actual_vnd : undefined;
      if (amount === undefined || BigInt(amount) <= 0n) continue;
      const rewritten = await ctx.attempt<Obj>(PREPARER, 'POST', '/funding-figures/batches', {
        project_id: String(project.project_id),
        class_code: String(cell.class_code),
        tier_code: String(cell.tier_code),
        measure: 'DISBURSED',
        figure_kind: 'ACTUAL',
        period_grain: 'MONTH',
        plan_year: priorYear,
        basis: 'REPORTED',
        as_of_date: ctx.day(0),
        entries: [{ period_ordinal: CORRECTED_MONTH, amount_vnd: (BigInt(amount) + RISE_VND).toString() }],
        explanation: text('books.explanation'),
      });
      if (!rewritten.ok) continue;
      const sent = await ctx.attempt<Obj>(PREPARER, 'POST', `/funding-figures/batches/${String(rewritten.json.resource_id)}/submission`, {}, { version: Number(rewritten.json.resource_version) });
      if (!sent.ok) continue;
      const accepted = await ctx.attempt('capApprover', 'POST', `/funding-figures/batches/${String(rewritten.json.resource_id)}/acceptance`, {}, { version: Number(sent.json.resource_version) });
      if (accepted.ok) {
        ctx.log(`  [crosscheck] ${String(project.project_code)} ${String(cell.class_code)} month ${CORRECTED_MONTH} of ${priorYear} reported again: ${amount} -> ${(BigInt(amount) + RISE_VND).toString()}`);
        return true;
      }
    }
  }
  return false;
}

/** The month reopened (requested by the owner, approved by the leader) so a second revision of its snapshot may be built. */
async function reopen(ctx: SeedContext, period: Obj): Promise<boolean> {
  const asked = await ctx.attempt<Obj>(REQUESTER, 'POST', `/reporting-periods/${String(period.id)}/reopen-requests`, { scope_kind: 'PERIOD', reason: text('reopen.reason'), window_hours: WINDOW_HOURS });
  if (!asked.ok) {
    ctx.warn(`the reopening of ${String(period.code)} was refused (HTTP ${asked.status})`);
    return false;
  }
  const decided = await ctx.attempt(DECIDER, 'POST', `/period-reopens/${String(asked.json.resource_id)}/decision`, { decision: 'approve', reason: text('reopen.decision'), window_hours: WINDOW_HOURS }, { version: Number(asked.json.resource_version) });
  if (!decided.ok) ctx.warn(`the reopening of ${String(period.code)} was not approved (HTTP ${decided.status})`);
  return decided.ok;
}

async function secondRevision(ctx: SeedContext, period: Obj): Promise<boolean> {
  const built = await ctx.attempt<Obj>(BUILDER, 'POST', '/enterprise-snapshots', { period_id: String(period.id) });
  if (!built.ok) {
    ctx.warn(`revision 2 of the snapshot of ${String(period.code)} could not be built (HTTP ${built.status} ${JSON.stringify(asObj(built.json).code ?? '')})`);
    return false;
  }
  const frozen = await ctx.attempt(FREEZER, 'POST', `/enterprise-snapshots/${String(built.json.resource_id)}/freeze`, {}, { version: Number(built.json.resource_version) });
  if (!frozen.ok) ctx.warn(`revision 2 of the snapshot of ${String(period.code)} could not be frozen (HTTP ${frozen.status})`);
  return frozen.ok;
}

export async function seedClipEnterpriseCrosscheck(ctx: SeedContext): Promise<void> {
  const plan = clipPlan() as unknown as (Block & { dataset?: string }) | undefined;
  if (plan === undefined || plan.dataset !== 'enterprise') {
    ctx.warn('no enterprise clip plan (CLIP_PLAN_FILE): the group has nothing to do');
    return;
  }
  const year = Number(plan.planYear);
  const periods = await ctx.step('DIS', `months of the enterprise calendar ${year}`, () => ensurePeriods(ctx, year));
  const period = periods.find((one) => monthOf(one) === MONTH);
  if (period === undefined) {
    ctx.warn(`the enterprise calendar ${year} has no month ${MONTH}`);
    return;
  }
  const label = String(period.code);
  const known = await ctx.list<Obj>(CHECKER, '/enterprise-snapshots', { period_id: String(period.id), limit: 50 });
  if (known.some((row) => row.status === 'FROZEN' && Number(row.revision) >= 2)) {
    ctx.log(`  [crosscheck] ${label} already has a second frozen revision`);
    await ctx.step('RPT', `${LAYOUT} ${periodCodeOf(year)} drafted and checked`, () => draftReport(ctx, year));
    return;
  }
  if (!(await ctx.step('DIS', `snapshot of ${label}`, () => freezeMonth(ctx, period, year, DEFAULT_PACE)))) return;
  const draft = await ctx.step('RPT', `${LAYOUT} ${periodCodeOf(year)} drafted and checked`, () => draftReport(ctx, year));
  if (draft === undefined) return;
  if (!(await ctx.step('FND', `books of ${year - 1} corrected`, () => correctBooks(ctx, year - 1)))) {
    ctx.warn('no actual of disbursement of the previous year could be reported again: no discrepancy');
    return;
  }
  const fresh = await ctx.get<Obj>(CHECKER, `/resources/reporting_period/${String(period.id)}`);
  if (!(await ctx.step('DIS', `reopen ${label}`, () => reopen(ctx, fresh)))) return;
  if (await ctx.step('DIS', `revision 2 of ${label}`, () => secondRevision(ctx, fresh))) {
    ctx.record({ module: 'RPT', screen: 'RPT-09', kind: 'crosscheck-draft', id: String(draft.id), code: `${LAYOUT} ${periodCodeOf(year)}`, note: 'report on revision 1, snapshot on revision 2' });
  }
}
