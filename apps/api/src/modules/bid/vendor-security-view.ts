import type { DeclarationRow, PendingConfirmation, SecurityEventRow, SecurityRow, SecurityStanding, SubcontractListing } from '@machvon/db';
import type { Caller } from './vendor-view';

/** The bid security as the screen reads it: the row, and what the caller may do next (the confirmation and the decision of a forfeiture belong to a person other than the one who received or proposed). */
export const securityDto = (row: SecurityRow, caller: Caller): Record<string, unknown> => ({
  id: row.id,
  package_id: row.packageId,
  package_code: row.packageCode,
  contractor_id: row.contractorId,
  contractor_name: row.contractorName,
  kind: row.kind,
  issuer: row.issuer,
  security_no: row.securityNo,
  amount: row.amount,
  issued_on: row.issuedOn,
  valid_until: row.validUntil,
  state: row.state,
  document_id: row.documentId,
  received_by: row.receivedBy,
  received_at: row.receivedAt,
  required_amount: row.requiredAmount,
  factor_applied: row.factorApplied,
  rule_version: row.ruleVersion,
  confirmed_by: row.confirmedBy,
  confirmed_at: row.confirmedAt,
  issuer_reference: row.issuerReference,
  rejected_by: row.rejectedBy,
  rejected_at: row.rejectedAt,
  reject_reason: row.rejectReason,
  forfeit_proposed_by: row.forfeitProposedBy,
  forfeit_proposed_at: row.forfeitProposedAt,
  forfeit_reason_code: row.forfeitReasonCode,
  forfeit_reason: row.forfeitReason,
  forfeit_decided_by: row.forfeitDecidedBy,
  forfeit_decided_at: row.forfeitDecidedAt,
  forfeit_decision_document_id: row.forfeitDecisionDocumentId,
  forfeit_decision_reason: row.forfeitDecisionReason,
  released_by: row.releasedBy,
  released_at: row.releasedAt,
  release_reason: row.releaseReason,
  expiry_facet: row.expiryFacet,
  conduct_behaviour: row.conductBehaviour,
  may_confirm: row.state === 'RECEIVED' && row.receivedBy !== caller.membershipId && caller.holds('vnd.security.confirm'),
  may_decide_forfeit: row.state === 'FORFEIT_PROPOSED' && row.forfeitProposedBy !== caller.membershipId && caller.holds('vnd.security.forfeit.decide'),
  version: row.version,
});

export const securityEventDto = (row: SecurityEventRow): Record<string, unknown> => ({ id: row.id, move: row.move, from_state: row.fromState, to_state: row.toState, actor_id: row.actorId, note: row.note, occurred_at: row.occurredAt });

export const standingDto = (packageId: string, contractorId: string, standing: SecurityStanding): Record<string, unknown> => ({
  package_id: packageId,
  contractor_id: contractorId,
  required_amount: standing.required.amount,
  factor: standing.required.factor,
  must_hold_until: standing.required.mustHoldUntil,
  factor_until: standing.required.basis.until,
  satisfied: standing.assessment.satisfied,
  gaps: standing.assessment.gaps,
  enforcement: standing.assessment.enforcement,
  shortfall: standing.assessment.shortfall,
});

export const declarationDto = (row: DeclarationRow): Record<string, unknown> => ({
  id: row.id,
  package_id: row.packageId,
  contractor_id: row.contractorId,
  declared_share_pct: row.declaredSharePct,
  subcontractor_ids: row.subcontractorIds,
  document_id: row.documentId,
  declared_by: row.declaredBy,
  declared_at: row.declaredAt,
});

export const pendingDto = (row: PendingConfirmation): Record<string, unknown> => ({
  subcontract_id: row.subcontractId,
  contract_id: row.contractId,
  contract_code: row.contractCode,
  subcontractor_id: row.subcontractorId,
  subcontractor_name: row.subcontractorName,
  payment_request_id: row.paymentRequestId,
  paid_on: row.paidOn,
  clock: row.clock,
});

export function subcontractListDto(listing: SubcontractListing, caller: Caller, policy: Record<string, unknown>, primeMinSharePct: number, asOf: string): Record<string, unknown> {
  return {
    contract_id: listing.contractId,
    contract_code: listing.contractCode,
    contract_value: listing.contractValue,
    prime_contractor_id: listing.primeContractorId,
    items: listing.items.map((row) => ({
      id: row.id,
      contract_id: row.contractId,
      contract_code: row.contractCode,
      subcontractor_id: row.subcontractorId,
      subcontractor_name: row.subcontractorName,
      scope: row.scope,
      value: row.value,
      share_pct: row.sharePct,
      declared_in_bid: row.declaredInBid,
      state: row.state,
      proposed_by: row.proposedBy,
      proposed_at: row.proposedAt,
      approved_by: row.approvedBy,
      approved_at: row.approvedAt,
      exception_reason: row.exceptionReason,
      exception_approved: row.exceptionApproved,
      findings: row.assessment?.findings ?? [],
      rule_version: row.ruleVersion,
      decided_by: row.decidedBy,
      decided_at: row.decidedAt,
      decision_reason: row.decisionReason,
      payments: row.payments.map((payment) => ({
        id: payment.id,
        payment_request_id: payment.paymentRequestId,
        paid_amount: payment.paidAmount,
        paid_on: payment.paidOn,
        reference: payment.reference,
        recorded_by: payment.recordedBy,
        recorded_at: payment.recordedAt,
        confirmed_by_subcontractor: payment.confirmedBySubcontractor,
        subcontractor_confirmed_at: payment.subcontractorConfirmedAt,
        clock: payment.clock,
      })),
      paid_total: row.paidTotal,
      over_paid: row.overPaid,
      may_approve: row.state === 'PROPOSED' && row.proposedBy !== caller.membershipId && caller.holds('vnd.subcontract.approve'),
      version: row.version,
    })),
    total_share_pct: listing.totalSharePct,
    prime_share_pct: listing.primeSharePct,
    prime_min_share_pct: primeMinSharePct,
    declaration: listing.declaration === null ? null : declarationDto(listing.declaration),
    pending: listing.pending.map(pendingDto),
    policy,
    as_of: asOf,
  };
}
